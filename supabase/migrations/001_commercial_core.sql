-- Central GO commercial core schema (prepared, not yet applied)
-- Designed for Supabase/PostgreSQL with multi-tenant Row Level Security.

create extension if not exists pgcrypto;

create type public.centralgo_global_role as enum ('super_admin', 'regional_partner', 'sales_partner');
create type public.centralgo_company_role as enum ('company_admin', 'operator', 'driver');
create type public.centralgo_driver_status as enum ('available', 'en_route', 'in_trip', 'paused', 'offline', 'sos');
create type public.centralgo_trip_status as enum ('pending', 'assigned', 'en_route', 'arrived', 'in_progress', 'completed', 'cancelled');
create type public.centralgo_payment_method as enum ('efectivo', 'transferencia', 'posnet_tarjeta', 'cuenta_corriente');
create type public.centralgo_vehicle_status as enum ('active', 'maintenance', 'inactive');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  phone text,
  avatar_url text,
  global_role public.centralgo_global_role,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.companies (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  code text not null unique,
  phone text,
  address text,
  vhf_frequency text,
  logo_url text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.company_memberships (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role public.centralgo_company_role not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (company_id, user_id, role)
);

create index company_memberships_user_idx on public.company_memberships(user_id, company_id) where active;

create table public.vehicles (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  unit_number text not null,
  license_plate text not null,
  brand text not null,
  model text not null,
  year integer not null check (year between 1950 and 2200),
  color text,
  capacity integer not null default 4 check (capacity between 1 and 20),
  pet_friendly boolean not null default false,
  wheelchair_accessible boolean not null default false,
  air_conditioning boolean not null default false,
  technical_inspection_expiry date,
  status public.centralgo_vehicle_status not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, unit_number),
  unique (company_id, license_plate)
);

create table public.drivers (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  vehicle_id uuid references public.vehicles(id) on delete set null,
  unit_number text not null,
  display_name text not null,
  phone text,
  license_number text not null,
  license_expiry date,
  photo_url text,
  status public.centralgo_driver_status not null default 'offline',
  rating numeric(3,2) not null default 5.00 check (rating between 0 and 5),
  total_trips_completed integer not null default 0 check (total_trips_completed >= 0),
  today_earnings numeric(14,2) not null default 0,
  commission_balance numeric(14,2) not null default 0,
  sos_active boolean not null default false,
  sos_timestamp timestamptz,
