-- Updated-at helper.
create or replace function public.centralgo_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_touch before update on public.profiles for each row execute function public.centralgo_touch_updated_at();
create trigger companies_touch before update on public.companies for each row execute function public.centralgo_touch_updated_at();
