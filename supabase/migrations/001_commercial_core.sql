create index drivers_company_status_idx on public.drivers(company_id, status);
create index drivers_user_idx on public.drivers(user_id) where user_id is not null;

create table public.driver_locations (
  driver_id uuid primary key references public.drivers(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  address text,
  speed_kmh numeric(7,2) check (speed_kmh is null or speed_kmh >= 0),
  heading_degrees numeric(6,2) check (heading_degrees is null or (heading_degrees >= 0 and heading_degrees < 360)),
  accuracy_meters numeric(8,2),
  recorded_at timestamptz not null default now()
