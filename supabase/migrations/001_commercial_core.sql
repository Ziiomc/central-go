create trigger drivers_touch before update on public.drivers for each row execute function public.centralgo_touch_updated_at();
create trigger clients_touch before update on public.clients for each row execute function public.centralgo_touch_updated_at();
create trigger fare_configs_touch before update on public.fare_configs for each row execute function public.centralgo_touch_updated_at();

-- Auth profile bootstrap. Never grants a privileged role automatically.
create or replace function public.centralgo_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, phone)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(coalesce(new.email, 'usuario'), '@', 1)),
    nullif(new.raw_user_meta_data ->> 'phone', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger centralgo_auth_user_created
after insert on auth.users
for each row execute procedure public.centralgo_handle_new_user();

-- Authorization helpers use SECURITY DEFINER to avoid recursive RLS evaluation.
create or replace function public.centralgo_is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.active and p.global_role = 'super_admin'
  );
$$;

create or replace function public.centralgo_is_company_member(target_company uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.centralgo_is_super_admin() or exists (
    select 1
    from public.company_memberships m
    where m.company_id = target_company
      and m.user_id = auth.uid()
      and m.active
  );
$$;

create or replace function public.centralgo_has_company_role(target_company uuid, allowed_roles public.centralgo_company_role[])
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.centralgo_is_super_admin() or exists (
    select 1
    from public.company_memberships m
    where m.company_id = target_company
      and m.user_id = auth.uid()
      and m.active
      and m.role = any(allowed_roles)
  );
$$;

